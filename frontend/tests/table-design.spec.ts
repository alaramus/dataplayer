import { expect, test } from "@playwright/test"
import type { Page } from "@playwright/test"

import { catalogAction, showOnlySchema } from "./utils/catalog"
import { createPostgresConnector } from "./utils/connectors"
import { login } from "./utils/login"
import { toast } from "./utils/notices"
import { deleteConnector, openConnector } from "./utils/workspace"

/** Choose one option of a kit select that is already on screen. */
async function choose(page: Page, field: string, option: string) {
  await page.getByTestId(field).click()
  await page.getByRole("option", { name: option, exact: true }).click()
}

/** One object of the definition, picked out of the left pane by its name. */
function object(page: Page, label: string) {
  return page.getByTestId("design-navigation").getByRole("button", { name: label })
}

test("designs a table, reviews the SQL, and only then creates it", async ({
  page,
}) => {
  const connector = `e2e-design-${Date.now()}`
  const table = `designed_${Date.now()}`
  await login(page)
  await createPostgresConnector(page, connector)
  await openConnector(page, connector)
  await showOnlySchema(page, "demo_lab")

  await catalogAction(page, "create_table")
  const designer = page.getByTestId("table-designer")
  await expect(designer).toContainText("demo_lab")

  await page.getByTestId("table-name").fill(table)

  // The first column, made a key the database numbers itself. The choice is
  // only offered on a type that can carry it, which is the server's rule.
  await page.getByTestId("column-name").fill("id")
  await choose(page, "column-type", "Integer")
  await choose(page, "column-generation", "Numbered by the database")

  // A second column, and the SQL follows without anything being created.
  await page.getByTestId("add-columns").click()
  await page.getByTestId("column-name").fill("label")
  await choose(page, "column-type", "Text")
  await page.getByTestId("column-not-null").click()

  const sql = page.getByTestId("design-sql")
  await expect(sql).toContainText("CREATE TABLE")
  await expect(sql).toContainText("GENERATED BY DEFAULT AS IDENTITY")

  // An index over the key the table already has is refused, by the server,
  // with the object named — and the review button goes with it.
  await page.getByTestId("add-indexes").click()
  await expect(page.getByTestId("design-problems")).toContainText(
    "The primary key already indexes those columns"
  )
  await expect(page.getByTestId("design-review-sql")).toBeDisabled()

  // Pointed at the other column, it is an index again.
  await choose(page, "index-key-column-0", "label")
  await expect(page.getByTestId("design-problems")).toBeHidden()

  // A check, built out of a column, a comparison and a typed value: there is
  // no field here that could hold a fragment of SQL.
  await page.getByTestId("add-constraints").click()
  await page.getByTestId("check-predicate-add").click()
  await page
    .getByTestId("check-predicate-term-0")
    .getByLabel("Comparison")
    .click()
  await page.getByRole("option", { name: "is not empty", exact: true }).click()
  await expect(sql).toContainText("CHECK")

  // Review replaces the editor rather than opening under it.
  await expect(page.getByTestId("design-review-sql")).toBeEnabled()
  await page.getByTestId("design-review-sql").click()
  await expect(page.getByTestId("design-navigation")).toBeHidden()
  const review = page.getByTestId("design-review")
  await expect(review).toContainText(`demo_lab.${table}`)
  await expect(review).toContainText("CREATE TABLE")
  await expect(review).toContainText("CREATE INDEX")

  // And going back leaves the draft exactly as it was.
  await page.getByTestId("design-back").click()
  await expect(page.getByTestId("design-navigation")).toBeVisible()
  await expect(object(page, "label")).toBeVisible()

  await page.getByTestId("design-review-sql").click()
  await page.getByTestId("design-create").click()
  await expect(toast(page, table)).toBeVisible()
  await expect(page.getByTestId("catalog-list")).toContainText(table)

  await deleteConnector(page, connector)
})

test("a draft that is closed asks first, and creates nothing", async ({ page }) => {
  const connector = `e2e-design-guard-${Date.now()}`
  await login(page)
  await createPostgresConnector(page, connector)
  await openConnector(page, connector)
  await showOnlySchema(page, "demo_lab")

  await catalogAction(page, "create_table")
  await page.getByTestId("table-name").fill("abandoned")

  await page.getByTestId("table-designer").getByRole("button", { name: "Cancel" }).click()
  await expect(page.getByTestId("confirm-message")).toContainText(
    "Nothing has been created"
  )
  await page.getByTestId("confirm-accept").click()

  await expect(page.getByTestId("table-designer")).toBeHidden()
  await expect(page.getByTestId("catalog-list")).not.toContainText("abandoned")

  await deleteConnector(page, connector)
})
