-- PostgreSQL feature-rich demo schema.
-- Re-runnable: it owns only the demo_lab schema.
BEGIN;

DROP SCHEMA IF EXISTS demo_lab CASCADE;
CREATE SCHEMA demo_lab;
SET search_path = demo_lab, public;

CREATE EXTENSION IF NOT EXISTS citext;
CREATE EXTENSION IF NOT EXISTS pgcrypto;

CREATE TYPE priority_level AS ENUM ('low', 'normal', 'high', 'critical');
CREATE TYPE task_status AS ENUM ('backlog', 'active', 'blocked', 'done', 'archived');
CREATE TYPE address AS (
    street text,
    city text,
    postal_code varchar(12),
    country char(2)
);

CREATE DOMAIN non_empty_text AS text CHECK (length(trim(VALUE)) > 0);
CREATE DOMAIN positive_amount AS numeric(14, 2) CHECK (VALUE >= 0);

CREATE TABLE organizations (
    organization_id bigint GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    public_id uuid NOT NULL DEFAULT gen_random_uuid(),
    slug citext NOT NULL UNIQUE,
    display_name varchar(120) NOT NULL,
    legal_name text,
    founded_on date,
    local_open time without time zone,
    local_close time with time zone,
    billing_cycle interval NOT NULL DEFAULT interval '1 month',
    timezone_name name NOT NULL DEFAULT 'UTC',
    headquarters address,
    service_area cidr,
    office_network inet,
    support_phone text,
    logo bytea,
    settings jsonb NOT NULL DEFAULT '{}'::jsonb,
    search_document tsvector GENERATED ALWAYS AS (
        to_tsvector('simple', coalesce(display_name, '') || ' ' || coalesce(legal_name, ''))
    ) STORED,
    created_at timestamptz NOT NULL DEFAULT now(),
    updated_at timestamp without time zone NOT NULL DEFAULT current_timestamp,
    CONSTRAINT organizations_slug_format CHECK (slug::text ~ '^[a-z0-9][a-z0-9-]+$')
);

CREATE TABLE app_users (
    user_id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    organization_id bigint NOT NULL REFERENCES organizations(organization_id) ON DELETE CASCADE,
    external_key uuid NOT NULL DEFAULT gen_random_uuid(),
    email citext NOT NULL,
    full_name non_empty_text NOT NULL,
    initials char(3),
    is_active boolean NOT NULL DEFAULT true,
    login_count integer NOT NULL DEFAULT 0 CHECK (login_count >= 0),
    reputation smallint NOT NULL DEFAULT 0,
    quota_bytes bigint NOT NULL DEFAULT 1073741824,
    hourly_rate money,
    completion_ratio real,
    satisfaction double precision,
    preferred_languages varchar(8)[] NOT NULL DEFAULT ARRAY[]::varchar(8)[],
    skills text[][],
    profile json,
    fingerprint bit varying(128),
    last_seen timestamptz,
    UNIQUE (organization_id, email)
);

CREATE TABLE teams (
    team_id bigint GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    organization_id bigint NOT NULL REFERENCES organizations(organization_id) ON DELETE CASCADE,
    name varchar(80) NOT NULL,
    parent_team_id bigint,
    budget positive_amount NOT NULL DEFAULT 0,
    metadata jsonb,
    UNIQUE (organization_id, name),
    FOREIGN KEY (parent_team_id) REFERENCES teams(team_id) ON DELETE SET NULL
);

CREATE TABLE team_members (
    team_id bigint NOT NULL REFERENCES teams(team_id) ON DELETE CASCADE,
    user_id bigint NOT NULL REFERENCES app_users(user_id) ON DELETE CASCADE,
    joined_at timestamptz NOT NULL DEFAULT now(),
    role_name varchar(40) NOT NULL DEFAULT 'member',
    allocation numeric(5, 2) NOT NULL DEFAULT 100 CHECK (allocation BETWEEN 0 AND 100),
    PRIMARY KEY (team_id, user_id)
);

CREATE TABLE projects (
    project_id bigint GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    organization_id bigint NOT NULL REFERENCES organizations(organization_id) ON DELETE CASCADE,
    owner_id bigint REFERENCES app_users(user_id) ON DELETE SET NULL,
    code char(8) NOT NULL,
    name varchar(150) NOT NULL,
    priority priority_level NOT NULL DEFAULT 'normal',
    status task_status NOT NULL DEFAULT 'backlog',
    budget numeric(15, 2),
    launch_date date,
    deadline timestamptz,
    duration interval,
    repository_url text,
    configuration jsonb NOT NULL DEFAULT '{}'::jsonb,
    UNIQUE (organization_id, code),
    CHECK (deadline IS NULL OR launch_date IS NULL OR deadline::date >= launch_date)
);

CREATE TABLE tasks (
    task_id bigint GENERATED ALWAYS AS IDENTITY,
    project_id bigint NOT NULL REFERENCES projects(project_id) ON DELETE CASCADE,
    parent_task_id bigint,
    assignee_id bigint REFERENCES app_users(user_id) ON DELETE SET NULL,
    title varchar(240) NOT NULL,
    description text,
    status task_status NOT NULL DEFAULT 'backlog',
    priority priority_level NOT NULL DEFAULT 'normal',
    estimate_hours numeric(8, 2),
    progress numeric(5, 2) NOT NULL DEFAULT 0 CHECK (progress BETWEEN 0 AND 100),
    due_at timestamptz,
    completed_at timestamp with time zone,
    location point,
    affected_area polygon,
    time_window tstzrange,
    recurrence int4range,
    labels text[] NOT NULL DEFAULT '{}',
    custom_fields jsonb NOT NULL DEFAULT '{}',
    title_search tsvector GENERATED ALWAYS AS (to_tsvector('simple', title || ' ' || coalesce(description, ''))) STORED,
    PRIMARY KEY (task_id),
    FOREIGN KEY (parent_task_id) REFERENCES tasks(task_id) ON DELETE CASCADE,
    CHECK (completed_at IS NULL OR status = 'done')
) PARTITION BY RANGE (task_id);

CREATE TABLE tasks_early PARTITION OF tasks FOR VALUES FROM (MINVALUE) TO (1000);
CREATE TABLE tasks_late PARTITION OF tasks FOR VALUES FROM (1000) TO (MAXVALUE);

CREATE TABLE tags (
    tag_id integer GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    organization_id bigint NOT NULL REFERENCES organizations(organization_id) ON DELETE CASCADE,
    label varchar(40) NOT NULL,
    color char(7) DEFAULT '#64748B',
    UNIQUE (organization_id, label),
    CHECK (color ~ '^#[0-9A-Fa-f]{6}$')
);

CREATE TABLE task_tags (
    task_id bigint NOT NULL REFERENCES tasks(task_id) ON DELETE CASCADE,
    tag_id integer NOT NULL REFERENCES tags(tag_id) ON DELETE CASCADE,
    added_by bigint REFERENCES app_users(user_id) ON DELETE SET NULL,
    added_at timestamptz NOT NULL DEFAULT now(),
    PRIMARY KEY (task_id, tag_id)
);

CREATE TABLE task_dependencies (
    predecessor_id bigint NOT NULL REFERENCES tasks(task_id) ON DELETE CASCADE,
    successor_id bigint NOT NULL REFERENCES tasks(task_id) ON DELETE CASCADE,
    dependency_kind varchar(16) NOT NULL DEFAULT 'blocks',
    lag interval NOT NULL DEFAULT interval '0 seconds',
    PRIMARY KEY (predecessor_id, successor_id),
    CHECK (predecessor_id <> successor_id)
);

CREATE TABLE measurements (
    measurement_id bigint GENERATED ALWAYS AS IDENTITY,
    organization_id bigint NOT NULL REFERENCES organizations(organization_id) ON DELETE CASCADE,
    measured_at timestamptz NOT NULL,
    metric_name varchar(80) NOT NULL,
    value_numeric numeric(20, 6),
    value_integer bigint,
    value_text text,
    unit varchar(16),
    reading bytea,
    PRIMARY KEY (measurement_id, measured_at)
) PARTITION BY RANGE (measured_at);

CREATE TABLE measurements_2025 PARTITION OF measurements
    FOR VALUES FROM ('2025-01-01') TO ('2026-01-01');
CREATE TABLE measurements_2026 PARTITION OF measurements
    FOR VALUES FROM ('2026-01-01') TO ('2027-01-01');

CREATE TABLE audit_events (
    event_id bigint GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    organization_id bigint REFERENCES organizations(organization_id) ON DELETE SET NULL,
    actor_id bigint REFERENCES app_users(user_id) ON DELETE SET NULL,
    occurred_at timestamptz NOT NULL DEFAULT now(),
    action varchar(64) NOT NULL,
    request_id uuid NOT NULL DEFAULT gen_random_uuid(),
    client_ip inet,
    client_mac macaddr,
    payload jsonb NOT NULL DEFAULT '{}',
    payload_xml xml,
    checksum bytea,
    CONSTRAINT audit_request_action UNIQUE (request_id, action)
);

CREATE TABLE documents (
    document_id uuid PRIMARY KEY DEFAULT gen_random_uuid(),
    organization_id bigint NOT NULL REFERENCES organizations(organization_id) ON DELETE CASCADE,
    uploaded_by bigint REFERENCES app_users(user_id) ON DELETE SET NULL,
    file_name varchar(255) NOT NULL,
    content_type varchar(120) NOT NULL,
    content bytea NOT NULL,
    content_length bigint GENERATED ALWAYS AS (octet_length(content)) STORED,
    sha256 char(64) NOT NULL,
    version integer NOT NULL DEFAULT 1,
    created_at timestamptz NOT NULL DEFAULT now(),
    UNIQUE (organization_id, sha256)
);

CREATE INDEX organizations_search_idx ON organizations USING gin (search_document);
-- jsonb_path_ops is intentionally used on the jsonb column, not on profile
-- (profile remains json to exercise both PostgreSQL document types).
CREATE INDEX organizations_settings_idx ON organizations USING gin (settings jsonb_path_ops);
CREATE INDEX tasks_title_search_idx ON tasks USING gin (title_search);
CREATE INDEX tasks_due_idx ON tasks (project_id, due_at) WHERE status <> 'done';
CREATE INDEX tasks_window_idx ON tasks USING gist (time_window);
CREATE INDEX measurements_metric_time_idx ON measurements (organization_id, metric_name, measured_at DESC);
CREATE INDEX audit_payload_idx ON audit_events USING gin (payload);

CREATE VIEW project_rollup AS
SELECT p.project_id, p.code, p.name, p.status, count(t.task_id) AS task_count,
       count(t.task_id) FILTER (WHERE t.status = 'done') AS completed_tasks,
       avg(t.progress)::numeric(5, 2) AS average_progress
FROM projects p LEFT JOIN tasks t ON t.project_id = p.project_id
GROUP BY p.project_id, p.code, p.name, p.status;

COMMENT ON SCHEMA demo_lab IS 'Complex PostgreSQL schema used for adapter and catalog testing';
COMMENT ON TABLE tasks IS 'Partitioned task hierarchy with arrays, ranges, geometry and generated search data';
COMMIT;
