# A parameter is data — a name, a number — and never a word to be translated:
# a word inside a parameter would reach a Russian sentence in English.
ProblemParam = str | int | float


class ProblemDetail(BaseModel):
    model_config = ConfigDict(extra="forbid")

    code: ProblemCode
    params: dict[str, ProblemParam]
    message: str
    # What a source refusal was reduced to, so the browser does not ask again
    # about what will be refused again (`config` for a missing capability).
    # Absent from the body when a refusal has none.
    error_kind: ErrorKind | None = None


class ProblemResponse(BaseModel):
    """What a refusal's body is: FastAPI puts an HTTPException's detail under
    `detail`."""

    detail: ProblemDetail


class Problem(HTTPException):
    """An HTTPException whose detail is a code, its parameters and the English."""

    def __init__(
        self,
        status_code: int,
        code: ProblemCode,
        *,
        headers: dict[str, str] | None = None,
        error_kind: ErrorKind | None = None,
        **params: ProblemParam,
    ) -> None:
        self.code: ProblemCode = code
        self.params = params
        detail = ProblemDetail(
            code=code,
            params=params,
            message=MESSAGES[code].format(**params),
            error_kind=error_kind,
        )
        super().__init__(
            status_code=status_code,
            detail=detail.model_dump(exclude_none=True),
            headers=headers,
        )
