from collections.abc import AsyncGenerator

import pytest

from app.adapters.content import ContentRequest, SqlContent
from app.adapters.postgres.adapter import PostgresAdapter
from app.adapters.postgres.content import MAX_DDL_BYTES, _bounded_utf8, _relation_ddl
from app.adapters.postgres.options import PostgresUserPassword
from app.adapters.protocol import NodeNotFound, SupportsContent
from tests.utils.database import working_postgres_options
from tests.utils.relation_fixture import make_schema


@pytest.fixture
async def schema() -> AsyncGenerator[str]:
    async for name in make_schema():
        yield name


def _adapter() -> PostgresAdapter:
    return PostgresAdapter(PostgresUserPassword(**working_postgres_options()))


def test_postgres_declares_the_content_capability() -> None:
    assert isinstance(_adapter(), SupportsContent)


async def test_a_table_ddl_uses_server_described_types_constraints_and_indexes(
    schema: str,
) -> None:
    result = await _adapter().read_content(
        ContentRequest(node_id=f"{schema}.customers", representation="sql")
    )

    assert isinstance(result, SqlContent)
    assert result.kind == "sql"
    assert f'CREATE TABLE "{schema}"."customers"' in result.text
    assert '"id" integer GENERATED BY DEFAULT AS IDENTITY' in result.text
    assert '"balance" numeric(10,2) DEFAULT 0 NOT NULL' in result.text
    assert 'CONSTRAINT "customers_region_fkey" FOREIGN KEY' in result.text
    assert f'CREATE INDEX customers_name_idx ON {schema}.customers' in result.text
    assert "COMMENT ON TABLE" in result.text
    assert "People who owe money" in result.text
    assert result.truncated is False
    assert result.notice is None


async def test_a_view_ddl_uses_the_server_deparser(schema: str) -> None:
    result = await _adapter().read_content(
        ContentRequest(node_id=f"{schema}.rich_customers", representation="sql")
    )

    assert isinstance(result, SqlContent)
    assert f'CREATE VIEW "{schema}"."rich_customers" AS' in result.text
    assert "balance >" in result.text
    assert "CREATE TABLE" not in result.text


async def test_partitioned_parent_and_child_keep_their_distinct_ddl(schema: str) -> None:
    parent = await _adapter().read_content(
        ContentRequest(node_id=f"{schema}.events", representation="sql")
    )
    child = await _adapter().read_content(
        ContentRequest(node_id=f"{schema}.events_2026", representation="sql")
    )

    assert isinstance(parent, SqlContent)
    assert "PARTITION BY RANGE (happened)" in parent.text
    assert isinstance(child, SqlContent)
    assert f'PARTITION OF "{schema}"."events"' in child.text
    assert "FOR VALUES FROM" in child.text


async def test_a_postgres_relation_refuses_another_content_viewer(schema: str) -> None:
    with pytest.raises(ValueError, match="does not offer"):
        await _adapter().read_content(
            ContentRequest(node_id=f"{schema}.customers", representation="json")
        )


async def test_a_relation_that_disappeared_is_not_found(schema: str) -> None:
    with pytest.raises(NodeNotFound):
        await _adapter().read_content(
            ContentRequest(node_id=f"{schema}.missing", representation="sql")
        )


def test_ddl_is_bounded_by_utf8_bytes_without_splitting_a_character() -> None:
    text, truncated = _bounded_utf8("x" * (MAX_DDL_BYTES - 1) + "€", MAX_DDL_BYTES)

    assert text == "x" * (MAX_DDL_BYTES - 1)
    assert len(text.encode("utf-8")) <= MAX_DDL_BYTES
    assert truncated is True


def test_catalog_names_and_comments_are_quoted_as_sql_values_not_templates() -> None:
    ddl = _relation_ddl(
        {
            "kind": "r",
            "persistence": "p",
            "is_partition": False,
            "schema_name": "odd schema",
            "relation_name": 'say"hi',
            "owner": 'role"name',
            "comment": "reader's table",
        },
        [
            {
                "name": 'value"name',
                "sql_type": "text",
                "not_null": False,
                "identity": "",
                "generated": "",
                "expression": None,
                "collation_schema": None,
                "collation_name": None,
            }
        ],
        [],
        [],
    )

    assert '"odd schema"."say""hi"' in ddl
    assert '"value""name" text' in ddl
    assert 'OWNER TO "role""name"' in ddl
    assert "IS 'reader''s table'" in ddl
